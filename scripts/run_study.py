from tcutune import identify as idf  # noqa: E402
from tcutune import metrics as me  # noqa: E402
from tcutune import plant  # noqa: E402
from tcutune import tuning as tu  # noqa: E402
from tcutune.tool import W, tune_zone  # noqa: E402

RES = ROOT / "results"
IMG = ROOT / "docs" / "img"

# validated categorical slots 1-3 (dataviz reference palette), ink + chrome
C1, C2, C3 = "#2a78d6", "#eb6834", "#1baf7a"
INK, INK2, MUTED, GRID, AXIS, SURF = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7", "#fcfcfb"

plt.rcParams.update({
    "figure.facecolor": SURF, "axes.facecolor": SURF, "savefig.facecolor": SURF,
    "axes.edgecolor": AXIS, "axes.labelcolor": INK2, "xtick.color": MUTED, "ytick.color": MUTED,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.spines.top": False,
    "axes.spines.right": False, "lines.linewidth": 2.0, "font.size": 10, "axes.titlesize": 11,
    "axes.titlecolor": INK, "legend.frameon": False, "legend.labelcolor": INK2,
})

VARIANTS = ("ratio 1 (one gain set)", "static Kc/Kh", "crossover ratio")


def true_ms(p: plant.ZoneParams, prm) -> tuple[float, float]:
    Gh = plant.linear_frf(p, W, "heat", 75.0)
    c0 = ex.cool_for(p, 80.0, p.q_run)
    Tw0, _ = plant.Zone(p).steady_state(0.0, c0, p.q_run)
    Gc = -plant.linear_frf(p, W, "cool", Tw0, c0)
    return (tu.max_sensitivity(prm, Gh, W),
            tu.max_sensitivity(prm, Gc / prm.CoolGainRatio, W))


def main() -> int:
    RES.mkdir(exist_ok=True)
    IMG.mkdir(parents=True, exist_ok=True)
    rows, runs_A, tunings = [], {}, {}

    for z in "ABCD":
        p = plant.with_noise(plant.PRESETS[z])
        heat = ex.heat_step_test(p, duration=5400)
        cool = ex.cool_step_test(p, duration=5400)
        relay = ex.relay_test(p, hyst=0.2)
        zt = tune_zone(heat, cool, relay, zone=z)
        tunings[z] = (zt, heat)
        cands = {c.name: c for c in zt.candidates if c.prm is not None}
        for name in ("lambda_pi", "tl_pi", "simc_ms1.4"):
            if name not in cands:
                continue
            base = cands[name].prm
            ratios = {VARIANTS[0]: 1.0, VARIANTS[1]: zt.ratio, VARIANTS[2]: base.CoolGainRatio}
            for var, r in ratios.items():
                if name == "lambda_pi" and var != VARIANTS[2]:
                    continue
                prm = replace(base, CoolGainRatio=r)
                run = ex.closed_loop(p, prm)
                seg = me.segments(run)
                tot = me.totals(seg)
                ms_h, ms_c = true_ms(plant.PRESETS[z], prm)
                rows.append({
                    "zone": z, "rule": name, "cooling": var, "Gain": round(prm.Gain, 2),
                    "Ti": round(prm.Ti, 1), "CoolGainRatio": round(r, 2),
                    "Ms_heat_true": round(ms_h, 2), "Ms_cool_true": round(ms_c, 2),
                    "IAE_total": round(tot["iae"]), "IAE_load_on": round(seg[2].iae),
                    "peak_load_on": round(seg[2].max_dev, 2),
                    "overshoot_SP_down": round(seg[3].max_dev, 2),
                    "overshoot_SP_up": round(seg[1].max_dev, 2),
                    "switchovers": tot["switchovers"], "TV": round(tot["tv"]),
                    "unsettled": tot["unsettled_segments"],
                })
                print(rows[-1])
                if z == "A":
                    runs_A[(name, var)] = run

    with open(RES / "study.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    write_markdown(rows, tunings)
    plot_identification(*tunings["A"])
    plot_scenario(runs_A)
    plot_cooling_zoom(runs_A)
    plot_ms(rows)
    return 0


def write_markdown(rows, tunings) -> None:
    out = ["# Study results (generated by scripts/run_study.py)", "",
           "Simulated zones with 0.05 K noise and 0.1 K resolution. Ms values are on the",
           "true linearised plant (heating at 75 degC, cooling at 80 degC with the process",
           "load on), which only a simulation can know.", "",
           "## Identified models and recommendation", ""]
    out.append("| Zone | FOPDT K, T, L | Lead-lag K, T1, T2, Ta, L | static Kc/Kh | recommended Gain, Ti, CoolGainRatio |")
    out.append("|---|---|---|---|---|")
    for z, (zt, _) in tunings.items():
        f, m, b = zt.fopdt, zt.model, zt.best()
        out.append(f"| {z} | {f.K:.2f}, {f.T:.0f} s, {f.L:.1f} s | {m.K:.2f}, {m.T1:.0f}, {m.T2:.0f}, "
                   f"{m.Ta:.0f}, {m.L:.1f} s | {zt.ratio:.2f} | {b.prm.Gain:.1f} %/K, {b.prm.Ti:.0f} s, "
                   f"{b.prm.CoolGainRatio:.2f} |")
    out += ["", "## Closed loop, production scenario", "",
            "| Zone | Rule | Cooling | Gain | Ti | Ratio | Ms heat | Ms cool | IAE total | IAE load-on | "
            "peak load-on K | overshoot SP-down K | switchovers |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['zone']} | {r['rule']} | {r['cooling']} | {r['Gain']} | {r['Ti']} | "
                   f"{r['CoolGainRatio']} | {r['Ms_heat_true']} | {r['Ms_cool_true']} | {r['IAE_total']} | "
                   f"{r['IAE_load_on']} | {r['peak_load_on']} | {r['overshoot_SP_down']} | {r['switchovers']} |")
    (RES / "study.md").write_text("\n".join(out) + "\n", encoding="utf-8")


def plot_identification(zt, heat) -> None:
    sd = idf.find_step(heat.t, heat.heat, heat.pv)
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.plot(sd.t / 60, sd.dy, color=MUTED, lw=1.0, label="recorded PV change (noise, 0.1 K steps)")
    ax.plot(sd.t / 60, zt.fopdt.step(sd.t, sd.du), color=C2,
            label=f"FOPDT fit: L = {zt.fopdt.L:.1f} s, RMSE {zt.fopdt.rmse:.3f} K")
    ax.plot(sd.t / 60, zt.model.step(sd.t, sd.du), color=C1,
            label=f"lead-lag fit: L = {zt.model.L:.1f} s, RMSE {zt.model.rmse:.3f} K")
    ins = ax.inset_axes([0.55, 0.12, 0.42, 0.42])
    m = sd.t <= 300
    ins.plot(sd.t[m], sd.dy[m], color=MUTED, lw=1.0)
    ins.plot(sd.t[m], zt.fopdt.step(sd.t[m], sd.du), color=C2)
    ins.plot(sd.t[m], zt.model.step(sd.t[m], sd.du), color=C1)
    ins.set_title("first 300 s (x in seconds)", fontsize=9, color=INK2)
    ins.tick_params(labelsize=8)
    ax.set_xlabel("time after heater step +10 % (min)")
    ax.set_ylabel("PV change (K)")
    ax.set_title("Zone A heater step: FOPDT misses the fast water mode, lead-lag fits both")
    ax.legend(loc="upper left", fontsize=9)
    fig.tight_layout()
    fig.savefig(IMG / "identification_zoneA.png", dpi=150)
    plt.close(fig)


def plot_scenario(runs) -> None:
    a = runs[("simc_ms1.4", VARIANTS[0])]
    b = runs[("simc_ms1.4", VARIANTS[2])]
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(9, 6), sharex=True,
                                   gridspec_kw={"height_ratios": [3, 2]})
    t = a.t / 60
    ax1.plot(t, a.sp, color=INK2, lw=1.2, ls="--", label="setpoint")
    ax1.plot(t, a.pv, color=C2, label="CoolGainRatio = 1")
    ax1.plot(t, b.pv, color=C1, label=f"CoolGainRatio = {b_ratio(b):.2f} (tool)")
    for name, te in a.scenario.events()[1:]:
        ax1.axvline(te / 60, color=AXIS, lw=0.8)
        ax1.text(te / 60 + 1, 84.6, name, color=MUTED, fontsize=8)
    ax1.set_ylim(50, 86)
    ax1.set_ylabel("temperature (degC)")
    ax1.set_title("Zone A, recommended PI (SIMC, Ms 1.4): production scenario on the nonlinear plant")
    ax1.legend(loc="lower right", fontsize=9)
    ax2.plot(t, b.heat, color=C1, lw=1.2, label="heater % (tool ratio)")
    ax2.plot(t, -b.cool, color=C3, lw=1.2, label="cooling valve % (shown negative)")
    ax2.set_ylabel("output (%)")
    ax2.set_xlabel("time (min)")
    ax2.legend(loc="lower left", fontsize=9)
    fig.tight_layout()
    fig.savefig(IMG / "scenario_zoneA.png", dpi=150)
    plt.close(fig)


def b_ratio(run) -> float:
    m = run.cool > 1.0
    k = int(np.argmax(m))
    return float(-run.u[k] / run.cool[k]) if m.any() else 1.0


def plot_cooling_zoom(runs) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
    for ax, rule, title in zip(axes, ("simc_ms1.4", "tl_pi"),
                               ("SIMC Ms 1.4 (recommended)", "Tyreus-Luyben from relay test")):
        a = runs[(rule, VARIANTS[0])]
        b = runs[(rule, VARIANTS[2])]
        m = (a.t >= 8300) & (a.t <= 9300)
        ax.plot(a.t[m] / 60, a.sp[m], color=INK2, lw=1.2, ls="--", label="setpoint")
        ax.plot(a.t[m] / 60, a.pv[m], color=C2, label="ratio 1")
        ax.plot(b.t[m] / 60, b.pv[m], color=C1, label="crossover ratio")
        ax.set_title(title)
        ax.set_xlabel("time (min)")
    axes[0].set_ylabel("temperature (degC)")
    axes[0].legend(fontsize=9, loc="upper right")
    fig.suptitle("Zone A, setpoint 80 -> 75 degC while the process load forces cooling",
                 color=INK, fontsize=11)
    fig.tight_layout()
    fig.savefig(IMG / "cooling_sp_down_zoneA.png", dpi=150)
    plt.close(fig)


def plot_ms(rows) -> None:
    zones = list("ABCD")
    fig, ax = plt.subplots(figsize=(8, 3.8))
    width = 0.26
    for i, (var, col) in enumerate(zip(VARIANTS, (C2, MUTED, C1))):
        vals = [next(r["Ms_cool_true"] for r in rows
                     if r["zone"] == z and r["rule"] == "simc_ms1.4" and r["cooling"] == var)
                for z in zones]
        x = np.arange(len(zones)) + (i - 1) * (width + 0.02)
        bars = ax.bar(x, vals, width, color=col, label=var)
        ax.bar_label(bars, fmt="%.2f", fontsize=8, color=INK2, padding=2)
    heat = [next(r["Ms_heat_true"] for r in rows
                 if r["zone"] == z and r["rule"] == "simc_ms1.4" and r["cooling"] == VARIANTS[2])
            for z in zones]
    ax.scatter(np.arange(len(zones)), heat, marker="_", s=900, color=INK, zorder=3,
               label="Ms in heating (same for all three)")
    ax.axhline(2.0, color=AXIS, lw=0.8, ls=":")
    ax.text(3.45, 2.03, "Ms = 2", color=MUTED, fontsize=8)
    ax.set_xticks(np.arange(len(zones)), [f"zone {z}" for z in zones])
    ax.set_ylabel("Ms in the cooling range (true plant)")
    ax.set_title("Robustness in cooling with the recommended PI, by cooling-gain setting")
    ax.legend(fontsize=8, loc="upper left", ncol=2)
    ax.set_ylim(0, max(4.0, ax.get_ylim()[1]))
    fig.tight_layout()
    fig.savefig(IMG / "ms_cooling.png", dpi=150)
    plt.close(fig)


