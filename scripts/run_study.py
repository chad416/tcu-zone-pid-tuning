"""Full study: identify + tune every zone, then run the production scenario on
the nonlinear plant with three cooling settings and check robustness against
the true (simulation-only) linear model.

Writes results/study.csv, results/study.md and docs/img/*.png.
Run:  PYTHONPATH=src python scripts/run_study.py
"""

from __future__ import annotations

