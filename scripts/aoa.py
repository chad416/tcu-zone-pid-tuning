"""Analysis of alternatives for the cooling path of a TCU zone (DOSSIER section 10).

Reads results/envelope.csv and results/time_domain.csv (written by run_study.py),
scores alternatives A-E on weighted criteria with linear utility curves, and
checks how the ranking moves when every weight is changed by +-10 points and
when the cost assumption is doubled.  Writes results/aoa.md.
"""

from __future__ import annotations

import csv
import itertools
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
ALTS = ["A", "B", "C", "D", "E"]
LABEL = {"A": "one gain set (ratio 1)", "B": "static gain ratio", "C": "crossover ratio (tool v0.1)",
         "D": "C + Tw-Tcw scaling", "E": "C + exchanger/valve model inversion (tool v0.2)"}

# cost per TCU (4 zones), EUR, assumed: Pt100 + transmitter + analog input in the cooling-water
# inlet, wiring, and engineering time (data entry and test) at 60 EUR/h
COST = {"A": 0.0, "B": 0.0, "C": 4 * 1 * 60.0, "D": 250.0 + 4 * 1.5 * 60.0, "E": 250.0 + 4 * 3.0 * 60.0}

WEIGHTS = {"robustness": 30, "corner performance": 25, "consistency": 15, "actuator wear": 10,
           "cost": 15, "PLC load": 5}


def util(x: float, good: float, bad: float) -> float:
    """Linear utility 100 at `good`, 0 at `bad`, clipped."""
    u = (x - bad) / (good - bad)
    return float(100.0 * min(max(u, 0.0), 1.0))


def load():
    env = list(csv.DictReader((RES / "envelope.csv").open()))
    td = list(csv.DictReader((RES / "time_domain.csv").open()))
    return env, td


def measures(env, td):
    m = {}
    for a in ALTS:
        e = [r for r in env if r["alt"] == a]
        ms_max = max(float(r["Ms_max"]) for r in e)
        ms_med = [float(r["Ms_median"]) for r in e]
        spread = float(np.mean([float(r["Ms_max"]) - float(r["Ms_min"]) for r in e]))
        corners = [r for r in td if r["alt"] == a and r["case"] != "test point"]
        if not corners:  # B and D are run at the test point only; use it
            corners = [r for r in td if r["alt"] == a]
        peak = float(np.mean([float(r["peak_load_on"]) for r in corners]))
        ovs = float(np.mean([float(r["overshoot_SP_down"]) for r in corners]))
        sw = float(np.mean([float(r["switchovers"]) for r in td if r["alt"] == a]))
        m[a] = {"Ms max (envelope, clean+fouled)": ms_max, "Ms median range": (min(ms_med), max(ms_med)),
                "Ms spread (mean max-min per zone)": spread, "corner load-on peak K": peak,
                "corner SP-down overshoot K": ovs, "switchovers per run": sw, "cost EUR per TCU": COST[a]}
    return m


def scores(m, cost_scale: float = 1.0):
    s = {}
    for a in ALTS:
        x = m[a]
        s[a] = {
            "robustness": util(x["Ms max (envelope, clean+fouled)"], 1.6, 3.0),
            "corner performance": 0.5 * util(x["corner load-on peak K"], 1.0, 3.0)
                                  + 0.5 * util(x["corner SP-down overshoot K"], 0.5, 2.5),
            "consistency": util(x["Ms spread (mean max-min per zone)"], 0.1, 1.0),
            "actuator wear": util(x["switchovers per run"], 20.0, 300.0),
            "cost": util(x["cost EUR per TCU"] * cost_scale, 0.0, 3000.0),
            "PLC load": 100.0 if a in ("A", "B", "C") else (90.0 if a == "D" else 70.0),
        }
    return s


def fom(s, w):
    tot = sum(w.values())
    return {a: sum(s[a][k] * w[k] for k in w) / tot for a in ALTS}


def main() -> int:
    env, td = load()
    m = measures(env, td)
    s = scores(m)
    f = fom(s, WEIGHTS)
    rank = sorted(ALTS, key=lambda a: -f[a])
    out = ["# Analysis of alternatives: cooling path of a TCU zone (generated by scripts/aoa.py)", "",
           "Measures from results/envelope.csv and results/time_domain.csv (simulation). Utility curves are",
           "linear between the stated good and bad values; weights sum to 100.", "",
           "## Measures", "",
           "| Alt | " + " | ".join(next(iter(m.values())).keys()) + " |",
           "|---|" + "---|" * len(next(iter(m.values())))]
    for a in ALTS:
        vals = []
        for v in m[a].values():
            vals.append(f"{v[0]:.2f}-{v[1]:.2f}" if isinstance(v, tuple) else f"{v:.2f}")
        out.append(f"| {a} {LABEL[a]} | " + " | ".join(vals) + " |")
    out += ["", "## Utility scores and figure of merit", "",
            "| Alt | " + " | ".join(f"{k} ({w})" for k, w in WEIGHTS.items()) + " | FOM |",
            "|---|" + "---|" * (len(WEIGHTS) + 1)]
    for a in rank:
        out.append(f"| {a} | " + " | ".join(f"{s[a][k]:.0f}" for k in WEIGHTS) + f" | **{f[a]:.1f}** |")
    out += ["", "Utility anchors: robustness Ms 1.6 -> 100, 3.0 -> 0; load-on peak 1 K -> 100, 3 K -> 0;",
            "SP-down overshoot 0.5 K -> 100, 2.5 K -> 0; Ms spread 0.1 -> 100, 1.0 -> 0; switchovers 20 -> 100,",
            "300 -> 0; cost 0 -> 100, 3000 EUR -> 0; PLC load by inspection of the budget (study section 7).", ""]

    # sensitivity: every weight +-10 points, one at a time
    flips = []
    for k, d in itertools.product(WEIGHTS, (-10, 10)):
        w = dict(WEIGHTS)
        w[k] = max(w[k] + d, 0)
        ff = fom(s, w)
        win = max(ALTS, key=lambda a: ff[a])
        flips.append((k, d, win, ff[win] - sorted(ff.values())[-2]))
    out += ["## Sensitivity", "", "| weight changed | by | winner | lead over second |", "|---|---|---|---|"]
    out += [f"| {k} | {d:+d} | {win} | {lead:.1f} |" for k, d, win, lead in flips]
    s2 = scores(m, cost_scale=2.0)
    f2 = fom(s2, WEIGHTS)
    win2 = max(ALTS, key=lambda a: f2[a])
    # weight on cost at which the winner changes
    cw = None
    for c in range(0, 101):
        w = dict(WEIGHTS)
        w["cost"] = c
        ff = fom(s, w)
        if max(ALTS, key=lambda a: ff[a]) != rank[0]:
            cw = c
            break
    out += ["", f"Cost doubled (sensor and engineering time): winner {win2} "
            f"(FOM {f2[win2]:.1f}).",
            f"Cost weight at which {rank[0]} stops winning (others fixed): "
            + (f"{cw}." if cw is not None else "not within 0-100."), "",
            "## Ranking", "", " > ".join(f"{a} ({f[a]:.1f})" for a in rank), ""]
    (RES / "aoa.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
